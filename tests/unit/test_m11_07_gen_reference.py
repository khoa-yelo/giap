"""``scripts/docs/gen_reference.py`` on small inputs in ``tmp_path`` (M11-07 item 3, acceptance 2).

Golden strings pin the Markdown format of each generated page. Interface the tests expect from the
script (loaded by path; it is not a package module):

- ``render_cli(group: click.Group, prog: str) -> str``
- ``render_configuration(defaults: Mapping[str, Any], schema: Mapping[str, Any]) -> str``
- ``render_tables(schemas_dir: Path) -> str``  (``datapackage.json`` + ``tables/*.schema.json``)
- ``render_flags(schemas_dir: Path) -> str``
- ``render_index(directory: Path, kind: str) -> str``  (``kind`` is ``"methods"`` or ``"adr"``)
- ``main(argv: list[str]) -> int``; module constants ``DOCS_DIR`` and ``SCHEMAS_DIR`` are read at
  call time (tests monkeypatch them). ``main`` writes ``DOCS_DIR/reference/{cli,configuration,
  tables,flags}.md``, ``DOCS_DIR/methods/index.md`` and ``DOCS_DIR/adr/index.md``.

Format rules pinned here: a ``# Title`` line, the comment line ``GENERATED``, then sections; empty
cells are an em dash; pipes outside code spans are escaped (``\\|``), pipes inside code spans are
not (Python-Markdown splits table rows on unescaped pipes outside code spans); LF; one trailing
newline.
"""

