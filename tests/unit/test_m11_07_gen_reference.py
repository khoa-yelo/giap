    rows = {r[0]: r for r in _rows(gr.render_tables(root))}
    for i, d in enumerate(descs):
        row = rows[f"f{i}"]
        assert len(row) == 5
        assert row[3] == (d or "—")
    assert rows["f0"][4] == f"pattern {pattern}"
