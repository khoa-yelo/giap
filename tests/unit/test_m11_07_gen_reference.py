def _snapshot(d: Path) -> dict[str, bytes]:
    return {
        p.relative_to(d).as_posix(): p.read_bytes() for p in sorted(d.rglob("*")) if p.is_file()
    }


def test_main_writes_every_page(gr: ModuleType, docs: Path) -> None:
    assert gr.main([]) == 0
    for rel in OUTPUTS:
        data = (docs / rel).read_bytes()
        assert data.endswith(b"\n") and not data.endswith(b"\n\n"), rel
        assert b"\r" not in data, rel
        data.decode("utf-8")


