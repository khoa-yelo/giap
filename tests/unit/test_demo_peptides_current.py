"""The quickstart demo peptide table stays current (#359 review S2).

``docs/tutorials/data/sim100k_peptides.tsv.gz`` is generated by
``scripts/docs/make_demo_peptides.py`` from giapsim SIM100K. Nothing else re-runs the generator, so
a later giapsim change could leave the committed table (and the checksums and size recorded in
``docs/tutorials/data/PROVENANCE.md``) silently stale. These tests run the generator's ``--check``
in-process and pin PROVENANCE.md to the committed file.

Runtime: one SIM100K simulation, about 2.5 s, so the file is unmarked and runs in the every-PR
fast suite (``-m "not slow and not calibration and not calibration_full and not e2e"``).
"""

from __future__ import annotations

import gzip
import hashlib
import importlib.util
import re
from pathlib import Path
from types import ModuleType

import pytest

REPO = Path(__file__).resolve().parents[2]
SCRIPT = REPO / "scripts" / "docs" / "make_demo_peptides.py"
DATA = REPO / "docs" / "tutorials" / "data"
TABLE = DATA / "sim100k_peptides.tsv.gz"
PROVENANCE = DATA / "PROVENANCE.md"


def _load_script() -> ModuleType:
    spec = importlib.util.spec_from_file_location("make_demo_peptides", SCRIPT)
    assert spec is not None and spec.loader is not None
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


@pytest.fixture(scope="module")
def script() -> ModuleType:
    return _load_script()


def _provenance_sha(label: str) -> str:
    text = PROVENANCE.read_text(encoding="utf-8")
    m = re.search(rf"^([0-9a-f]{{64}})\s+{re.escape(label)}\s*$", text, flags=re.M)
    assert m, f"PROVENANCE.md has no sha256 line for {label!r}"
    return m.group(1)


def _provenance_size() -> int:
    text = PROVENANCE.read_text(encoding="utf-8")
    m = re.search(r"^- Size: ([\d,]+) bytes\.", text, flags=re.M)
    assert m, "PROVENANCE.md has no '- Size: N bytes.' line"
    return int(m.group(1).replace(",", ""))


def test_script_targets_the_committed_table(script: ModuleType) -> None:
    assert Path(script.OUT).resolve() == TABLE.resolve()
    assert TABLE.is_file()


def test_committed_table_matches_giapsim(
    script: ModuleType, capsys: pytest.CaptureFixture[str]
) -> None:
    """``make_demo_peptides.py --check`` (uncompressed comparison) passes on the committed table.

    A failure means giapsim (or its SIM100K defaults) changed: regenerate with
    ``python scripts/docs/make_demo_peptides.py`` and update PROVENANCE.md.
    """
    rc = script.main(["--check"])
    out = capsys.readouterr().out
    assert rc == 0, f"demo table is stale: {out.strip()}"
    assert "up to date" in out


def test_committed_table_within_size_limit(script: ModuleType) -> None:
    assert TABLE.stat().st_size <= script.MAX_BYTES


def test_provenance_size_matches_committed_file() -> None:
    assert _provenance_size() == TABLE.stat().st_size


def test_provenance_tsv_sha_matches_uncompressed_table() -> None:
    table = gzip.decompress(TABLE.read_bytes())
    assert hashlib.sha256(table).hexdigest() == _provenance_sha(
        "sim100k_peptides.tsv (uncompressed)"
    )


def test_provenance_gz_sha_matches_committed_file() -> None:
    """The gz checksum is of the committed bytes, so it is stable on every machine.

    Re-compressing the table can give other bytes with another zlib build (which is why ``--check``
    compares uncompressed), but this test hashes the committed file as is; it never re-compresses.
    It fails when someone regenerates the .gz and forgets the PROVENANCE.md line.
    """
    assert hashlib.sha256(TABLE.read_bytes()).hexdigest() == _provenance_sha(
        "sim100k_peptides.tsv.gz"
    )
