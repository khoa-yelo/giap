"""Shared pieces of the M8-13 golden gate, half 1 (docs/specs/M8-13-golden-equivalence.md;
ADR-0038, ADR-0044).

- Readers of the committed R golden data ``tests/data/golden/r/`` (M8-12) and of the exact
  Wallenius reference ``tests/data/golden/wallenius/exact_tails.tsv.gz`` (ADR-0044 decision 1).
- :func:`golden_r_tol` reads ``tolerances.yaml`` ``golden_r`` (never copied, R3).
- :func:`urn_pmf`: the Wallenius pmf from its definition (ADR-0044 "R1", the urn recursion):
  N sequential draws without replacement, a red ball drawn with probability
  ω·r / (ω·r + w). Every term is a sum of products of positive factors, so nothing cancels.
  Written for this test from the definition; no goseq, BiasedUrn or scipy code.
- :func:`update_report` merges one section into ``local/logs/golden/m8_golden.json`` (§5).
"""

from __future__ import annotations

import csv
import fcntl
import gzip
import json
import math
import os
from pathlib import Path
from typing import Any

import numpy as np
import yaml

REPO = Path(__file__).resolve().parents[2]
GOLDEN = REPO / "tests" / "data" / "golden" / "r"
EXACT_TAILS = REPO / "tests" / "data" / "golden" / "wallenius" / "exact_tails.tsv.gz"
TOLERANCES = REPO / "tests" / "calibration" / "tolerances.yaml"
REPORT = REPO / "local" / "logs" / "golden" / "m8_golden.json"
TAILS = ("over", "under")


def read_gz(path: Path) -> list[dict[str, str]]:
    """Rows of a gzipped TSV as strings (R's ``NA`` kept as the string ``NA``)."""
    assert path.is_file(), f"missing {path.relative_to(REPO)}"
    with gzip.open(path, "rt", encoding="utf-8", newline="") as fh:
        return list(csv.DictReader(fh, delimiter="\t", quoting=csv.QUOTE_NONE))


def num(cell: str) -> float:
    return math.nan if cell == "NA" else float(cell)


def golden_r_tol() -> dict[str, float]:
    return dict(yaml.safe_load(TOLERANCES.read_text(encoding="utf-8"))["golden_r"])


def golden_seed() -> int:
    return int(yaml.safe_load(TOLERANCES.read_text(encoding="utf-8"))["seeds"]["GOLDEN_SEED"])


def read_exact_tails() -> dict[tuple[str, str], float]:
    """ADR-0044's committed reference: (category, tail) -> exact p. Layout assumed from the ADR
    ("category, tail, 17-digit value"): a header whose first two names are ``category`` and
    ``tail`` (``over`` or ``under``) and whose third column is the value."""
    assert EXACT_TAILS.is_file(), (
        f"missing {EXACT_TAILS.relative_to(REPO)}: ADR-0044 decision 1 commits it, generated by "
        "scripts/golden/make_wallenius_exact.py on Slurm, with a PROVENANCE entry"
    )
    with gzip.open(EXACT_TAILS, "rt", encoding="utf-8", newline="") as fh:
        rows = list(csv.reader(fh, delimiter="\t"))
    header, body = rows[0], rows[1:]
    assert len(header) == 3 and header[:2] == ["category", "tail"], header
    out: dict[tuple[str, str], float] = {}
    for cat, tail, value in body:
        assert tail in TAILS, tail
        assert (cat, tail) not in out, (cat, tail)
        out[(cat, tail)] = float(value)
    return out


def urn_pmf(M: int, n: int, N: int, odds: float) -> np.ndarray:
    """pmf[x] = P(X = x), x = 0..min(n, N), for X ~ Wallenius(M, n, N, odds) by the urn
    recursion over the N draws (float64)."""
    m2 = M - n
    probs = np.ones(1)
    for t in range(N):
        r = np.arange(probs.size, dtype=np.float64)  # reds drawn so far
        red = odds * (n - r)
        white = np.maximum(m2 - (t - r), 0.0)
        den = red + white
        p_red = np.divide(red, den, out=np.zeros_like(den), where=den > 0)
        p_white = np.divide(white, den, out=np.zeros_like(den), where=den > 0)
        new = np.zeros(min(probs.size + 1, n + 1))
        new[: probs.size] += probs * p_white
        new[1 : probs.size + 1] += (probs * p_red)[: new.size - 1]
        probs = new
    return probs


def urn_tails(k: int, M: int, n: int, N: int, odds: float) -> tuple[float, float]:
    """(P(X >= k), P(X <= k)) from :func:`urn_pmf`, each a correctly rounded sum."""
    pmf = urn_pmf(M, n, N, odds)
    return math.fsum(pmf[k:].tolist()), math.fsum(pmf[: k + 1].tolist())


def decade(p: float) -> str:
    """Decade label of a p-value: ``"0"`` for p in (0.1, 1], ``"k"`` for (10^-(k+1), 10^-k],
    ``"zero"`` for p = 0, ``"NA"`` for NaN."""
    if math.isnan(p):
        return "NA"
    if p <= 0.0:
        return "zero"
    return str(max(0, math.ceil(-math.log10(p)) - 1))


def _session() -> str:
    """The test session writing the report: the Slurm job (if any) and the xdist run id, which
    every worker of one pytest run shares."""
    job = os.environ.get("SLURM_JOB_ID", "local")
    return f"{job}:{os.environ.get('PYTEST_XDIST_TESTRUNUID', os.getpid())}"


def update_report(section: str, payload: dict[str, Any], *, merge: bool = False) -> Path:
    """Write ``payload`` as ``section`` of the §5 JSON report (file-locked, xdist-safe);
    ``merge`` updates the section's existing fields instead of replacing it."""
    REPORT.parent.mkdir(parents=True, exist_ok=True)
    with (REPORT.parent / ".m8_golden.lock").open("w") as lock:
        fcntl.flock(lock, fcntl.LOCK_EX)
        data = json.loads(REPORT.read_text(encoding="utf-8")) if REPORT.is_file() else {}
        old = data.get(section, {})
        if old.get("session") != _session():  # never mix fields from an earlier run (#297 review)
            old = {}
        data[section] = {**(old if merge else {}), **payload, "session": _session()}
        REPORT.write_text(json.dumps(data, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    return REPORT
