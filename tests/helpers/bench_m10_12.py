@dataclass
class Bench:
    """A sandbox ready for ``benchmark_standard.sbatch``."""

    sb: Sandbox
    commit: str
    nodetmp: Path

    @property
    def root(self) -> Path:
        return self.sb.root

    @property
    def state(self) -> Path:
        return self.sb.state

    @property
    def bench_dir(self) -> Path:
        return self.sb.root / "bench"

    def configure(self, **cfg: Any) -> None:
        base: dict[str, Any] = {"commit": self.commit, "node": NODE}
        p = self.state / "bench_cfg.json"
        if p.is_file():
            base.update(json.loads(p.read_text()))
        base.update(cfg)
        p.write_text(json.dumps(base))

    def jsonl(self, name: str) -> list[Any]:
        return self.sb.jsonl(name)

    def giap_runs(self) -> list[dict[str, Any]]:
        return [r for r in self.jsonl("giap.jsonl") if r["argv"][:1] == ["run"]]

    def run(
        self,
        task: int = 0,
        *,
        unset: tuple[str, ...] = (),
        timeout: float = 240,
        **env: str,
    ) -> subprocess.CompletedProcess[str]:
        base = {
            "SLURM_ARRAY_TASK_ID": str(task),
            "SLURM_ARRAY_JOB_ID": ARRAY_JOB,
            "SLURM_JOB_ID": str(JOB_BASE + task),
            "SLURM_ARRAY_TASK_COUNT": "3",
            "SLURM_CPUS_PER_TASK": "16",
            "SLURM_MEM_PER_NODE": "64000",
            "SLURM_JOB_NAME": "giap-bench",
            "SLURMD_NODENAME": NODE,
            "SLURM_JOB_NODELIST": NODE,
            "SLURM_SUBMIT_DIR": str(self.sb.tmp),
            "FAKE_HOSTNAME": NODE,
            "TMPDIR": str(self.nodetmp),
            "BENCH_COMMIT": self.commit,
            "BENCH_ID": "2026-10-30_" + self.commit[:7],
        }
        script = self.sb.repo / "scripts" / "slurm" / "benchmark_standard.sbatch"
        return self.sb.run(["bash", str(script)], env={**base, **env}, unset=unset,
                           timeout=timeout)  # fmt: skip

    def run_dirs(self, bench_id: str | None = None) -> list[Path]:
        root = self.bench_dir / (bench_id or "2026-10-30_" + self.commit[:7])
        return sorted(p.parent for p in root.glob("r*/*/bench_run.json"))

    def record(self, rel: str, bench_id: str | None = None) -> dict[str, Any]:
        root = self.bench_dir / (bench_id or "2026-10-30_" + self.commit[:7])
        p = root / rel / "bench_run.json"
        assert p.is_file(), f"no {p.relative_to(self.root)}; found {self.run_dirs(bench_id)}"
        return json.loads(p.read_text())


def _git(repo: Path, env: dict[str, str], *args: str) -> str:
    res = subprocess.run(["git", "-C", str(repo), *args], env=env, capture_output=True,
                         text=True, check=True)  # fmt: skip
    return res.stdout.strip()


def commit_files(sb: Sandbox, files: dict[str, bytes], message: str = "inputs") -> str:
    """Write ``files`` into the sandbox repo, commit, push to its origin; return the new SHA."""
    for rel, data in files.items():
        p = sb.repo / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_bytes(data)
    _git(sb.repo, sb.env, "add", "-A")
    _git(sb.repo, sb.env, "commit", "-q", "-m", message)
    _git(sb.repo, sb.env, "push", "-q", "origin", "HEAD:main")
    return _git(sb.repo, sb.env, "rev-parse", "HEAD")


def commit_without_bench_record(sb: Sandbox) -> str:
    """A ``BENCH_COMMIT`` older than ``bench_record.py``: the commit has no
    ``scripts/dev/bench_record.py`` and a ``scripts/measure_runtimes.py`` that raises on import;
    the sandbox checkout (``$GIAP_REPO``) keeps both files as they are. Returns the SHA."""
    rec = sb.repo / "scripts" / "dev" / "bench_record.py"
    mr = sb.repo / "scripts" / "measure_runtimes.py"
    good_mr = mr.read_bytes()
    good_rec = rec.read_bytes() if rec.is_file() else None
    if good_rec is not None:
        rec.unlink()  # commit_files stages with `git add -A`
    mr.write_text('raise ImportError("an older measure_runtimes.py (pinned BENCH_COMMIT)")\n')
    sha = commit_files(sb, {}, "an older commit")
    mr.write_bytes(good_mr)
    if good_rec is not None:
        rec.write_bytes(good_rec)
    return sha


def make_bench(tmp: Path) -> Bench:
    sb = make_sandbox(tmp)
    py = sys.executable
    stubs = {"srun": _SRUN, "timeout": _TIMEOUT, "giap": _GIAP, "sacct": _SACCT,
             "squeue": _SQUEUE, "scontrol": _SCONTROL}  # fmt: skip
    for name, text in stubs.items():
        write_exe(sb.bin / name, text.replace("{common}", _COMMON).replace("{python}", py))
    write_exe(sb.bin / "sleep", _SLEEP)
    write_exe(sb.bin / "hostname", _HOSTNAME)
    env_sh = sb.repo / "scripts" / "farmshare_env.sh"
    env_sh.write_text(env_sh.read_text() + _ENV_EXTRA)
    commit = commit_files(
        sb,
        {
            K12_GENOME_REL: K12_GENOME.read_bytes(),
            K12_JSON_REL: K12_JSON.read_bytes(),
            "tests/sim/giapsim/__init__.py": _FAKE_GIAPSIM_INIT.encode(),
            "tests/sim/giapsim/simulate.py": _FAKE_GIAPSIM_SIMULATE.encode(),
            "scripts/farmshare_env.sh": env_sh.read_bytes(),
        },
        "bench inputs",
    )
    root = sb.root
    mv = root / "mvp04" / "20261023"
    mv.mkdir(parents=True)
    (mv / "peptides.tsv").write_text("peptide\tintensity\nPEPTIDEK\t1.0\n")
    (mv / "config.yaml").write_text("mapping:\n  enzyme: trypsin_p\n")
    (root / "db").mkdir()
    (root / "containers").mkdir()
    (root / "containers" / "bakta.img").write_text("image")
    (root / "mamba" / "nxf-envs" / "env-old").mkdir(parents=True)
    nodetmp = tmp / "nodetmp"
    nodetmp.mkdir()
    bench = Bench(sb=sb, commit=commit, nodetmp=nodetmp)
    bench.configure()
    return bench


def planned_lines(stdout: str) -> list[list[str]]:
    """Dry-run lines with ``srun`` and ``giap run``, tokenised from ``srun`` on."""
    out = []
    for ln in stdout.splitlines():
        if "srun" in ln and "giap run" in ln.replace("giap  run", "giap run"):
            toks = shlex.split(ln[ln.index("srun") :])
            out.append(toks)
    return out


def giap_argv(tokens: list[str]) -> list[str]:
    """The ``giap run …`` part of a planned or logged command line."""
    for i in range(len(tokens) - 1):
        if Path(tokens[i]).name == "giap" and tokens[i + 1] == "run":
            return tokens[i:]
    raise AssertionError(f"no giap run in {tokens}")


def gz_variant(data: bytes) -> bytes:
    """Same decompressed content plus one extra line: a different sha256."""
    return gzip.compress(gzip.decompress(data) + b"\n")


