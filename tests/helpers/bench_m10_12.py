def cell_of(argv: list[str]) -> str | None:
    """``…/<genome>_<variant>/out`` of ``--outdir`` → ``<genome>/<variant>``."""
    out = None
    for i, a in enumerate(argv):
        if a == "--outdir" and i + 1 < len(argv):
            out = argv[i + 1]
        elif a.startswith("--outdir="):
            out = a.split("=", 1)[1]
    if out is None:
        return None
    name = Path(out.rstrip("/")).parent.name
    genome, _, variant = name.rpartition("_")
    return f"{genome}/{variant}" if genome else None


def run_dir_of(argv: list[str]) -> Path | None:
    for i, a in enumerate(argv):
        if a == "--outdir" and i + 1 < len(argv):
            return Path(argv[i + 1]).parent
        if a.startswith("--outdir="):
            return Path(a.split("=", 1)[1]).parent
    return None


def flag(argv: list[str], name: str) -> str | None:
    """Value of ``--name V`` / ``--name=V`` (last wins)."""
    val = None
    for i, a in enumerate(argv):
        if a == name and i + 1 < len(argv):
            val = argv[i + 1]
        elif a.startswith(name + "="):
            val = a.split("=", 1)[1]
    return val


def sets(argv: list[str]) -> list[str]:
    return [argv[i + 1] for i, a in enumerate(argv) if a == "--set" and i + 1 < len(argv)] + [
        a.split("=", 1)[1] for a in argv if a.startswith("--set=")
    ]


