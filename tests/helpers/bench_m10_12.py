def bench_run(
    genome: str = "k12",
    variant: str = "standard",
    repeat: int = 1,
    attempt: str = "a",
    wall_s: float | None = 3912,
    *,
    status: str = "ok",
    exit_code: int = 0,
    invalid_reasons: list[str] | None = None,
    steps: dict[str, dict[str, float]] | None = None,
    node: str = NODE,
    max_rss_bytes: int | None = 21_600_000 * 1024,
    task_peak: int = int(20.6 * GIB),
    total_cpu_s: float | None = None,
    inputs_sha: str = "a" * 64,
    commit: str = "1f567901" + "0" * 32,
    n_failed: int = 0,
) -> dict[str, Any]:
    """A schema-complete ``bench_run.json`` record (spec "Interface")."""
    k = repeat
    modules = [] if variant == "standard" else ["--modules", "core"]
    extra = ["--set", "annotation.bakta.db=full"] if variant == "standard" else [
        "--annotation", f"/bench/inputs/{genome}.json"]  # fmt: skip
    argv = ["giap", "run", "--genome", f"/bench/inputs/{genome}.fna.gz", "--peptides", "p.tsv",
            *extra, *modules, "--db-dir", "/db", "--threads", "16", "--memory", "56.GB",
            "--profile", "farmshare_local,apptainer", "--seed", str(SEED), "--outdir",
            f"/bench/r{k}/{genome}_{variant}/out"]  # fmt: skip
    el = None if wall_s is None else int(wall_s)
    return {
        "schema": "giap-bench-run/1",
        "bench_id": "2026-10-30_1f56790",
        "commit": commit,
        "genome": genome,
        "variant": variant,
        "repeat": repeat,
        "attempt": attempt,
        "order_index": 0,
        "job_id": f"{ARRAY_JOB}_{repeat - 1}",
        "array_task": repeat - 1,
        "step_id": 0,
        "node": node,
        "cpu_sku": "CPU_SKU:6148",
        "argv": argv,
        "inputs": {"genome": {"path": f"/bench/inputs/{genome}.fna.gz", "sha256": inputs_sha}},
        "sacct": {
            "elapsed_s": el,
            "max_rss_bytes": max_rss_bytes,
            "total_cpu_s": total_cpu_s if total_cpu_s is not None
            else (None if el is None else 0.75 * el * 16),
            "alloc_cpus": 16,
            "state": "COMPLETED" if status == "ok" else "FAILED",
        },
        "script_wall_s": wall_s,
        "wall_s": wall_s,
        "exit_code": exit_code,
        "status": status,
        "invalid_reasons": invalid_reasons or [],
        "warnings": [],
        "trace": {
            "n_tasks": 5,
            "n_cached": 0,
            "n_failed": n_failed,
            "n_retried": 0,
            "hosts": [node],
            "task_peak_rss_max_bytes": task_peak,
        },
        "steps": steps if steps is not None else {
            "bakta": {"realtime_s": 600.0, "peak_rss_bytes": int(20.6 * GIB)},
            "operons": {"realtime_s": 180.0, "peak_rss_bytes": 2 * GIB},
        },
        "cotenancy": {"samples": 3, "node_cpualloc_median": 64, "node_cpualloc_max": 78,
                      "giap_other": []},
    }  # fmt: skip


def write_runs(bench: Path, runs: list[dict[str, Any]]) -> None:
    """``bench/r<k>[.<attempt>]/<genome>_<variant>/bench_run.json`` in the documented layout."""
    for r in runs:
        rep = f"r{r['repeat']}" + ("" if r["attempt"] == "a" else f".{r['attempt']}")
        d = bench / rep / f"{r['genome']}_{r['variant']}"
        d.mkdir(parents=True, exist_ok=True)
        (d / "bench_run.json").write_text(json.dumps(r, indent=2, sort_keys=True) + "\n")
