"""Fakes, a sandbox and run-record builders for the M10-12 benchmark tests.

docs/specs/M10-12-benchmark-standard.md (lead decisions: every L1-L12 takes its default).
Nothing here reaches Slurm, the network, a container or the real ``$GIAP_ROOT``: the sandbox
builds on ``helpers.slurm_sandbox.make_sandbox`` (a throw-away checkout of ``scripts/`` and
``ci/`` with a local bare ``origin``) and replaces the Slurm fakes with stateful ones.

Conventions settled by the test author (where the spec leaves the mechanism open):

* **Stubs on PATH** (``$GIAP_ROOT/venv/bin``, first on ``PATH``): ``srun`` (logs, numbers its
  steps from 0, exports ``SLURM_STEP_ID``/``SLURM_CPUS_PER_TASK=16``/``SLURM_MEM_PER_NODE=64000``
  and execs the command), ``timeout`` (logs; execs the command or returns a configured 124/137),
  ``giap`` (``setup --check`` and ``run``), ``sacct`` (per-step rows as real Slurm prints them
  for an array task: ``JobID`` is ``<array job>_<task>.<step>``, ``JobIDRaw`` is
  ``<job>.<step>``; ``-j`` accepts the raw ID, the array form or ``<id>.<step>``), ``squeue``
  (``%A|%j|%C|%N`` lines; the benchmark's own job is always listed; **another user's**
  ``giap-*`` job on the same node is listed too when the call has no ``-u``/``--user``/``--me``),
  ``scontrol show node`` (node totals and features), ``hostname`` and ``sleep`` (0.05 s whatever
  the argument, so the 5-min sampler and the sacct retries do not stall the tests).
* Stub switches per cell (``Bench.configure``): ``giap`` takes ``no_manifest`` (no
  ``run_manifest.json``) and ``commit_absent`` (a manifest without ``git_commit``) besides the
  older ones; ``sacct`` takes ``incomplete_calls: N`` (the first N queries of the step print a
  row with ElapsedRaw, AllocCPUS and State still empty).
* ``scripts/dev/bench_record.py`` (review of PR #300, finding 13) is run from ``$GIAP_REPO``,
  the submitting checkout, never from the pinned worktree: ``commit_without_bench_record``
  commits a ``BENCH_COMMIT`` that lacks it (and whose ``measure_runtimes.py`` cannot be
  imported) while the sandbox checkout keeps both.
* The **cell** of a call is read from its ``--outdir``: ``…/<genome>_<variant>/out``.
* The **K-12 input check**: the script (or a file under ``scripts/``) pins the sha256 of the two
  committed files (``K12_GENOME_SHA256``, ``K12_JSON_SHA256`` below); a checkout whose files
  differ from the pin exits 2.
* **SIM5M** is generated by importing ``giapsim`` from the pinned worktree's ``tests/sim``
  (``from giapsim import SIM5M, SIM5M_SEED, simulate`` or ``from giapsim.simulate import …``),
  never by an installed copy; the sandbox puts a tiny fake ``giapsim`` there that records the
  seed and writes ``genome.fasta``, ``bakta_like.json`` and ``peptides.tsv``.
* Planned lines of a dry run are stdout lines that contain ``srun`` and ``giap run``; they are
  read with ``shlex`` from the ``srun`` token on.
"""

