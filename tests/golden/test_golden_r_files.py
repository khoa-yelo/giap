"""The committed R golden data, ``tests/data/golden/r/`` (M8-12 acceptance "test_golden_r_files";
§11.5, R11). M8-13 consumes these files.

Layout assumed (names the spec leaves open):

- ``inputs/``: the four files of ``scripts/golden/make_golden_inputs.py`` (see
  tests/unit/test_golden_r_inputs.py), byte-identical to a fresh run at ``GOLDEN_SEED``.
- ``outputs/fgsea.tsv.gz``: ``pathway pval log2err ES NES size leadingEdge``
  (fgseaMultilevel; ``leadingEdge`` ``;``-joined; R's missing value written ``NA``).
- ``outputs/calc_gsea_stat.tsv.gz``: ``pathway ES`` (calcGseaStat for every set with ≥ 1
  member present in the scores).
- ``outputs/goseq.tsv.gz``: ``category over_represented_pvalue under_represented_pvalue
  numDEInCat numInCat`` (one row per input category).
- ``VERSIONS.txt`` (sessionInfo, packageVersion of fgsea/goseq/BiasedUrn, the lock sha256) and
  ``PROVENANCE.md`` (§11.4 template).

Every test skips, with the reason, until the implementer's ``giap-golden-r`` Slurm job has
committed the files.
"""

from __future__ import annotations

import csv
import gzip
import hashlib
import math
import re
import subprocess
import sys
from collections import defaultdict
from pathlib import Path

import pytest

REPO = Path(__file__).resolve().parents[2]
ROOT = REPO / "tests" / "data" / "golden" / "r"
INPUTS = ROOT / "inputs"
OUTPUTS = ROOT / "outputs"
LOCK = REPO / "scripts" / "golden" / "golden_r.explicit.txt"
GENERATOR = REPO / "scripts" / "golden" / "make_golden_inputs.py"
INPUT_FILES = ["gsea_sets.tsv.gz", "gsea_stats.tsv.gz", "ora_categories.tsv.gz", "ora_genes.tsv.gz"]
OUTPUT_COLUMNS = {
    "fgsea.tsv.gz": ["pathway", "pval", "log2err", "ES", "NES", "size", "leadingEdge"],
    "calc_gsea_stat.tsv.gz": ["pathway", "ES"],
    "goseq.tsv.gz": [
        "category",
        "over_represented_pvalue",
        "under_represented_pvalue",
        "numDEInCat",
        "numInCat",
    ],
}
FIVE_MB = 5 * 1024 * 1024
ONE_MB = 1024 * 1024

pytestmark = pytest.mark.skipif(
    not (OUTPUTS / "fgsea.tsv.gz").is_file(),
    reason="tests/data/golden/r/ not committed yet: generated by the giap-golden-r Slurm job "
    "(scripts/slurm/golden_r.sbatch, M8-12)",
)


def read_tsv(path: Path) -> tuple[list[str], list[list[str]]]:
    assert path.is_file(), f"missing {path.relative_to(REPO)}"
    with gzip.open(path, "rt", newline="") as fh:
        rows = list(csv.reader(fh, delimiter="\t"))
    return rows[0], rows[1:]


def num(x: str) -> float:
    return math.nan if x == "NA" else float(x)


def _long(path: Path) -> dict[str, list[str]]:
    out: dict[str, list[str]] = defaultdict(list)
    for key, member in read_tsv(path)[1]:
        out[key].append(member)
    return dict(out)


@pytest.fixture(scope="module")
def stats() -> dict[str, float]:
    return {r[0]: float(r[1]) for r in read_tsv(INPUTS / "gsea_stats.tsv.gz")[1]}


@pytest.fixture(scope="module")
def sets() -> dict[str, list[str]]:
    return _long(INPUTS / "gsea_sets.tsv.gz")


@pytest.fixture(scope="module")
def fgsea() -> dict[str, dict[str, str]]:
    header, rows = read_tsv(OUTPUTS / "fgsea.tsv.gz")
    return {r[0]: dict(zip(header, r, strict=True)) for r in rows}


@pytest.fixture(scope="module")
def goseq() -> dict[str, dict[str, str]]:
    header, rows = read_tsv(OUTPUTS / "goseq.tsv.gz")
    return {r[0]: dict(zip(header, r, strict=True)) for r in rows}


# --- presence, format, size (R11) ----------------------------------------------------------


def test_every_file_is_present() -> None:
    for name in INPUT_FILES:
        assert (INPUTS / name).is_file(), name
    for name in OUTPUT_COLUMNS:
        assert (OUTPUTS / name).is_file(), name
    assert (ROOT / "VERSIONS.txt").is_file()
    assert (ROOT / "PROVENANCE.md").is_file()


def test_sizes_and_gzip() -> None:
    files = [p for p in ROOT.rglob("*") if p.is_file()]
    for path in files:
        assert path.stat().st_size <= FIVE_MB, path
        if path.suffix == ".gz":
            assert path.read_bytes()[:2] == b"\x1f\x8b", path
        else:
            assert path.suffix in {".txt", ".md"}, f"only gzip text fixtures: {path}"
    assert sum(p.stat().st_size for p in OUTPUTS.iterdir()) <= ONE_MB, "outputs ≤ 1 MB total"
    assert sum(p.stat().st_size for p in files) < FIVE_MB


@pytest.mark.parametrize(("name", "columns"), sorted(OUTPUT_COLUMNS.items()))
def test_output_headers(name: str, columns: list[str]) -> None:
    header, rows = read_tsv(OUTPUTS / name)
    assert header == columns
    assert all(len(r) == len(columns) for r in rows)
    keys = [r[0] for r in rows]
    assert len(keys) == len(set(keys)), "one row per set/category"


def test_committed_inputs_equal_a_fresh_generation(tmp_path: Path, golden_seed: int) -> None:
    proc = subprocess.run(
        [sys.executable, str(GENERATOR), "--out", str(tmp_path), "--seed", str(golden_seed)],
        capture_output=True,
        text=True,
        cwd=REPO,
    )
    assert proc.returncode == 0, proc.stderr
    for name in INPUT_FILES:
        assert (tmp_path / name).read_bytes() == (INPUTS / name).read_bytes(), name


# --- fgsea outputs -------------------------------------------------------------------------


def test_fgsea_rows_are_the_sets_kept_by_the_size_filter(
    fgsea: dict[str, dict[str, str]], sets: dict[str, list[str]], stats: dict[str, float]
) -> None:
    assert len(sets) == 120
    kept = {s for s, m in sets.items() if 10 <= sum(x in stats for x in m) <= 500}
    assert set(fgsea) == kept
    for s, row in fgsea.items():
        assert int(row["size"]) == sum(x in stats for x in sets[s])


def test_fgsea_values_are_in_range(
    fgsea: dict[str, dict[str, str]], sets: dict[str, list[str]]
) -> None:
    for s, row in fgsea.items():
        p, es, nes, err = (num(row[c]) for c in ("pval", "ES", "NES", "log2err"))
        assert 0 < p <= 1, (s, p)
        assert -1 <= es <= 1 and es != 0, (s, es)
        assert math.isnan(nes) or math.copysign(1, nes) == math.copysign(1, es), s
        assert math.isnan(err) or err >= 0, s
        edge = row["leadingEdge"].split(";")
        assert edge and set(edge) <= set(sets[s]), s


def test_fgsea_p_values_span_the_planted_range(fgsea: dict[str, dict[str, str]]) -> None:
    ps = [num(r["pval"]) for r in fgsea.values()]
    assert min(ps) <= 1e-25, "planted sets reach p ~1e-30"
    assert any(1e-3 < p <= 1e-2 for p in ps)
    nan_err = sum(math.isnan(num(r["log2err"])) for r in fgsea.values())
    assert nan_err <= 0.05 * len(fgsea), "M8-13 caps NA log2err at 5 %"


def test_numbers_are_written_round_trip_exact(fgsea: dict[str, dict[str, str]]) -> None:
    # format(x, digits = 17): the small p-values keep more than double-rounding precision.
    es_digits = [
        len(re.sub(r"[^0-9]", "", r["ES"].split("e")[0].lstrip("-0."))) for r in fgsea.values()
    ]
    assert max(es_digits) >= 15


def test_calc_gsea_stat_covers_every_matched_set_and_agrees_with_fgsea(
    fgsea: dict[str, dict[str, str]], sets: dict[str, list[str]], stats: dict[str, float]
) -> None:
    _, rows = read_tsv(OUTPUTS / "calc_gsea_stat.tsv.gz")
    es = {r[0]: float(r[1]) for r in rows}
    assert set(es) == {s for s, m in sets.items() if any(x in stats for x in m)}
    for s, row in fgsea.items():
        assert abs(es[s] - float(row["ES"])) <= 1e-12, s


# --- goseq outputs -------------------------------------------------------------------------


def test_goseq_counts_match_the_inputs(goseq: dict[str, dict[str, str]]) -> None:
    detected = {r[0]: int(r[2]) for r in read_tsv(INPUTS / "ora_genes.tsv.gz")[1]}
    cats = _long(INPUTS / "ora_categories.tsv.gz")
    assert len(cats) == 150
    assert set(goseq) == set(cats)
    for c, members in cats.items():
        assert int(goseq[c]["numInCat"]) == len(members), c
        assert int(goseq[c]["numDEInCat"]) == sum(detected[g] for g in members), c


def test_goseq_p_values(goseq: dict[str, dict[str, str]]) -> None:
    over = [num(r["over_represented_pvalue"]) for r in goseq.values()]
    under = [num(r["under_represented_pvalue"]) for r in goseq.values()]
    assert all(0 <= p <= 1 for p in over + under)
    assert min(over) <= 1e-30, "planted enrichments down to ~1e-40"
    for r in goseq.values():
        k, n = int(r["numDEInCat"]), int(r["numInCat"])
        if k == 0:
            assert num(r["over_represented_pvalue"]) == pytest.approx(1.0)
        if k == n:
            assert num(r["under_represented_pvalue"]) == pytest.approx(1.0)


# --- versions and provenance ---------------------------------------------------------------


def test_versions_name_the_pins() -> None:
    text = (ROOT / "VERSIONS.txt").read_text()
    assert re.search(r"R version 4\.5\.\d", text)
    for package, version in (("fgsea", "1.36.2"), ("goseq", "1.62.0"), ("BiasedUrn", "2.0.12")):
        assert re.search(rf"{package}\D{{0,20}}{re.escape(version)}", text), package
    if LOCK.is_file():
        assert hashlib.sha256(LOCK.read_bytes()).hexdigest() in text


def test_provenance_records_the_run(golden_seed: int) -> None:
    text = (ROOT / "PROVENANCE.md").read_text()
    assert "GOLDEN_SEED" in text and str(golden_seed) in text
    assert re.search(r"[Jj]ob\D{0,20}\d{5,}", text), "Slurm job ID"
    assert re.search(r"\b[0-9a-f]{64}\b", text), "env lock sha256"
    assert re.search(r"commit\W{0,3}[0-9a-f]{40}\b", text), "git commit of the scripts"
    assert re.search(r"\b20\d\d-\d\d-\d\d\b", text), "date"
    assert "golden_r.sbatch" in text or "make_golden_r.R" in text, "command"
    if LOCK.is_file():
        assert hashlib.sha256(LOCK.read_bytes()).hexdigest() in text
