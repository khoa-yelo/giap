"""Generate the MkDocs reference pages from code and schemas (M11-07 item 3).

Usage: python scripts/docs/gen_reference.py [--check]

Writes docs/reference/{cli,configuration,tables,flags}.md, docs/methods/index.md and
docs/adr/index.md. ``--check`` writes nothing: it exits 1 with a unified diff when a committed page
differs from what the sources generate, and warns (exit 0) about table fields without a description.
"""

from __future__ import annotations

import argparse
import difflib
import html
import json
import re
import sys
from collections.abc import Mapping
from pathlib import Path
from typing import Any, cast

import click
import yaml

REPO = Path(__file__).resolve().parents[2]
DOCS_DIR = REPO / "docs"
SCHEMAS_DIR = REPO / "src" / "giap" / "schemas"
CONFIG_SCHEMA = REPO / "src" / "giap" / "schemas" / "config.schema.json"
DEFAULTS = REPO / "src" / "giap" / "config" / "defaults.yaml"

GENERATED = "<!-- Generated by scripts/docs/gen_reference.py; do not edit. -->"
DASH = "—"


# --- Markdown helpers ---------------------------------------------------------------------------


def _code(text: str) -> str:
    """A code span; pipes inside it need no escape (Python-Markdown tables skip code spans)."""
    return f"`{text}`"


def _prose(text: str) -> str:
    """Whitespace collapsed; outside `code spans` (kept as written) ``&<>`` are HTML-escaped and
    ``*`` and any ``_`` not inside a word (the ones Python-Markdown reads as emphasis) are
    backslash-escaped, so they show as text."""
    parts = re.split(r"(`[^`]*`)", " ".join(text.split()))
    return "".join(
        p if i % 2 else re.sub(r"\*|(?<!\w)_|_(?!\w)", r"\\\g<0>", html.escape(p, quote=False))
        for i, p in enumerate(parts)
    )


def _text(text: str | None) -> str:
    """Prose for a table cell: escaped as in ``_prose``, pipes escaped, empty as an em dash."""
    flat = _prose(text or "")
    return flat.replace("|", "\\|") if flat else DASH


def _row(cells: list[str]) -> str:
    return "| " + " | ".join(cells) + " |"


def _table(head: list[str], rows: list[list[str]]) -> list[str]:
    return [_row(head), "|" + "---|" * len(head), *(_row(r) for r in rows)]


def _page(title: str, body: list[str]) -> str:
    lines = [f"# {title}", "", GENERATED, "", *body]
    while lines and lines[-1] == "":
        lines.pop()
    return "\n".join(lines) + "\n"


def _json(value: Any) -> str:
    return value if isinstance(value, str) else json.dumps(value, ensure_ascii=False)


# --- CLI ----------------------------------------------------------------------------------------


def _unset(value: Any) -> bool:
    """No default: ``None`` or Click 8.3's ``UNSET`` sentinel."""
    return value is None or type(value).__name__ == "Sentinel"


def _param_names(p: click.Parameter) -> str:
    if isinstance(p, click.Option):
        names = ", ".join(_code(o) for o in p.opts)
        if p.secondary_opts:
            names += " / " + ", ".join(_code(o) for o in p.secondary_opts)
        return names
    return _code(p.human_readable_name)


def _param_type(p: click.Parameter) -> str:
    if isinstance(p, click.Option) and p.is_flag:
        return "flag"
    if p.metavar:
        return _code(p.metavar)
    return _code(p.type.name.upper())


def _param_default(p: click.Parameter) -> str:
    if p.required:
        return "required"
    default = p.default
    if callable(default):
        # Dynamic defaults are described, never evaluated on the build machine.
        show = getattr(p, "show_default", None)
        return _text(show) if isinstance(show, str) else DASH
    if _unset(default) or (isinstance(default, (list, tuple)) and not default):
        return DASH
    if isinstance(p, click.Option) and p.is_flag:
        if not default and not p.secondary_opts:
            return DASH
        return _code(json.dumps(bool(default)))
    return _code(_json(default))


def _param_choices(p: click.Parameter) -> str:
    choices = p.type.choices if isinstance(p.type, click.Choice) else []
    return ", ".join(_code(str(c)) for c in choices) or DASH


def _help(text: str | None) -> list[str]:
    """Paragraphs of a command help, whitespace collapsed."""
    paras = (" ".join(para.split()) for para in re.split(r"\n\s*\n", (text or "").strip()))
    return [para for para in paras if para]


def render_cli(group: click.Group, prog: str) -> str:
    """Every visible command of ``group`` (Click's list order) and its visible parameters."""
    body: list[str] = []
    for para in _help(group.help):
        body += [para, ""]
    ctx = click.Context(group, info_name=prog)
    for name in group.list_commands(ctx):
        cmd = group.get_command(ctx, name)
        if cmd is None or cmd.hidden:
            continue
        body += [f"## {prog} {name}", ""]
        for para in _help(cmd.help):
            body += [para, ""]
        rows = [
            [
                _param_names(p),
                _param_type(p),
                _param_default(p),
                _param_choices(p),
                _text(getattr(p, "help", None)),
            ]
            for p in cmd.params
            if not getattr(p, "hidden", False)
        ]
        if rows:
            body += [*_table(["Option", "Type", "Default", "Choices", "Help"], rows), ""]
    return _page("CLI reference", body)


# --- configuration ------------------------------------------------------------------------------


def _resolve(node: Mapping[str, Any], defs: Mapping[str, Any]) -> Mapping[str, Any]:
    while "$ref" in node:
        node = defs[str(node["$ref"]).rsplit("/", 1)[-1]]
    return node


def _schema_type(node: Mapping[str, Any] | None, defs: Mapping[str, Any]) -> str:
    if node is None:
        return DASH
    node = _resolve(node, defs)
    if "enum" in node:
        return "one of " + ", ".join(_code(_json(v)) for v in node["enum"])
    if "const" in node:
        return _code(_json(node["const"]))
    kind = node.get("type")
    if isinstance(kind, str):
        return kind
    if "anyOf" in node:
        return " or ".join(_schema_type(n, defs) for n in node["anyOf"])
    return DASH


def _child(
    node: Mapping[str, Any] | None, key: str, defs: Mapping[str, Any]
) -> Mapping[str, Any] | None:
    child = _resolve(node, defs).get("properties", {}).get(key) if node is not None else None
    return child if isinstance(child, Mapping) else None


def _leaves(
    values: Mapping[str, Any], node: Mapping[str, Any] | None, prefix: str, defs: Mapping[str, Any]
) -> list[list[str]]:
    rows: list[list[str]] = []
    for key, value in values.items():
        dotted = f"{prefix}{key}"
        sub = _child(node, str(key), defs)
        if isinstance(value, Mapping) and value:
            rows += _leaves(value, sub, dotted + ".", defs)
            continue
        desc = sub.get("description") if sub is not None else None
        rows.append(
            [
                _code(dotted),
                _code(_json(value)),
                _schema_type(sub, defs),
                _text(desc if isinstance(desc, str) else None),
            ]
        )
    return rows


def render_configuration(defaults: Mapping[str, Any], schema: Mapping[str, Any]) -> str:
    """Every key of ``defaults.yaml``, grouped by top-level section, typed from the schema."""
    defs: Mapping[str, Any] = schema.get("$defs", {})
    head = ["Key", "Default", "Type", "Description"]
    top = {k: v for k, v in defaults.items() if not (isinstance(v, Mapping) and v)}
    body: list[str] = []
    if top:
        body += ["## Top level", "", *_table(head, _leaves(top, schema, "", defs)), ""]
    for key, value in defaults.items():
        if isinstance(value, Mapping) and value:
            rows = _leaves(value, _child(schema, str(key), defs), f"{key}.", defs)
            body += [f"## {_code(str(key))}", "", *_table(head, rows), ""]
    return _page("Configuration reference", body)


# --- tables and flags ---------------------------------------------------------------------------


def _read_json(path: Path) -> dict[str, Any]:
    return cast(dict[str, Any], json.loads(path.read_text(encoding="utf-8")))


def _table_entries(schemas_dir: Path) -> list[tuple[str, str | None, str | None, dict[str, Any]]]:
    """(schema path, resource path, coordinates, schema): datapackage resources in their order,
    then the ``tables/*.schema.json`` no resource names, sorted by file name."""
    package = _read_json(schemas_dir / "datapackage.json")
    out: list[tuple[str, str | None, str | None, dict[str, Any]]] = []
    seen: set[str] = set()
    for res in package.get("resources", []):
        rel = str(res["schema"])
        schema = _read_json(schemas_dir / rel)
        seen.add(rel)
        coords = res.get("coordinates", schema.get("coordinates"))
        out.append((rel, str(res["path"]), coords, {"name": res["name"], **schema}))
    for path in sorted((schemas_dir / "tables").glob("*.schema.json")):
        rel = path.relative_to(schemas_dir).as_posix()
        if rel not in seen:
            schema = _read_json(path)
            out.append((rel, None, schema.get("coordinates"), schema))
    return out


def _coordinates(value: str | None) -> str:
    return value.replace("based-", "based ") if value else DASH


def _constraints(constraints: Mapping[str, Any]) -> str:
    parts: list[str] = []
    for key, value in constraints.items():
        if key in ("required", "unique"):
            if value:
                parts.append(key)
        elif key == "enum":
            parts.append("one of " + ", ".join(_code(_json(v)) for v in value))
        elif key == "pattern":
            parts.append(f"pattern {_code(str(value))}")
        elif isinstance(value, (int, float, str)) and not isinstance(value, bool):
            parts.append(f"{key} {_json(value)}")
        else:
            parts.append(f"{key} {_code(_json(value))}")
    return "; ".join(parts) or DASH


def render_tables(schemas_dir: Path, missing: list[str] | None = None) -> str:
    """One section per datapackage resource and per unlisted table schema; ``missing`` collects
    the ``table.field`` names that have no description."""
    body: list[str] = []
    for rel, path, coords, schema in _table_entries(schemas_dir):
        body += [f"## {_code(str(schema['name']))}", ""]
        if schema.get("description"):
            body += [_prose(str(schema["description"])), ""]
        body += [
            f"- Path: {_code(path) if path else DASH}",
            f"- Coordinates: {_coordinates(coords)}",
            f"- Schema: {_code(rel)}",
            "",
        ]
        rows = [
            [
                _code(str(f["name"])),
                _text(f.get("type")),
                _text(f.get("unit")),
                _text(f.get("description")),
                _constraints(f.get("constraints") or {}),
            ]
            for f in schema.get("fields", [])
        ]
        if missing is not None:
            missing += [
                f"{schema['name']}.{f['name']}"
                for f in schema.get("fields", [])
                if not str(f.get("description") or "").strip()
            ]
        body += [*_table(["Field", "Type", "Unit", "Description", "Constraints"], rows), ""]
    return _page("Output tables", body)


def _alternatives(pattern: str) -> list[str]:
    """The alternatives of a flat ``(?:a|b)(?:;(?:a|b))*`` flags pattern."""
    m = re.match(r"\(\?:([^()]*)\)", pattern)
    return m.group(1).split("|") if m else []


def render_flags(schemas_dir: Path) -> str:
    """The flag vocabulary of every table with a ``flags`` field (§9.4)."""
    body: list[str] = []
    for _, _, _, schema in _table_entries(schemas_dir):
        for field in schema.get("fields", []):
            if field.get("name") != "flags":
                continue
            cons = field.get("constraints") or {}
            tokens = [str(v) for v in cons["enum"]] if "enum" in cons else []
            if not tokens and "pattern" in cons:
                tokens = _alternatives(str(cons["pattern"]))
            body += [f"## {_code(str(schema['name']))}", ""]
            body += [f"- {_code(t)}" for t in tokens] or ["No fixed vocabulary in the schema."]
            body.append("")
    return _page("Flag vocabulary", body or ["No entries."])


# --- methods and ADR indexes --------------------------------------------------------------------


def _title(text: str, fallback: str) -> str:
    titles = (line[2:].strip() for line in text.splitlines() if line.startswith("# "))
    return next(titles, fallback)


def _status(text: str) -> str | None:
    """The ADR status: the ``- Status:`` item up to its first sentence end."""
    lines = text.splitlines()
    for i, line in enumerate(lines):
        if line.startswith("- Status:"):
            parts = [line.removeprefix("- Status:")]
            j = i + 1
            while j < len(lines) and lines[j][:1].isspace() and lines[j].strip():
                parts.append(lines[j])
                j += 1
            flat = " ".join(" ".join(parts).split())
            depth = 0
            for k, ch in enumerate(flat):
                depth += {"(": 1, ")": -1}.get(ch, 0)
                if ch == "." and depth == 0 and flat[k + 1 : k + 2] in (" ", ""):
                    return flat[:k]
            return flat
    return None


def render_index(directory: Path, kind: str) -> str:
    """Title list of ``directory`` (``kind`` ``"methods"`` or ``"adr"``)."""
    title, pattern = ("Decisions", "ADR-*.md") if kind == "adr" else ("Methods", "*.md")
    items: list[str] = []
    for path in sorted(directory.glob(pattern)):
        if path.name == "index.md":
            continue
        text = path.read_text(encoding="utf-8")
        item = f"- [{_title(text, path.stem)}]({path.name})"
        status = _status(text) if kind == "adr" else None
        items.append(f"{item}: {status}" if status else item)
    return _page(title, items or ["No entries."])


# --- main ---------------------------------------------------------------------------------------


def _pages(missing: list[str]) -> dict[str, str]:
    from giap.cli import cli

    defaults = yaml.safe_load(DEFAULTS.read_text(encoding="utf-8"))
    return {
        "reference/cli.md": render_cli(cli, "giap"),
        "reference/configuration.md": render_configuration(defaults, _read_json(CONFIG_SCHEMA)),
        "reference/tables.md": render_tables(SCHEMAS_DIR, missing),
        "reference/flags.md": render_flags(SCHEMAS_DIR),
        "methods/index.md": render_index(DOCS_DIR / "methods", "methods"),
        "adr/index.md": render_index(DOCS_DIR / "adr", "adr"),
    }


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(prog="gen_reference.py", description=__doc__)
    parser.add_argument("--check", action="store_true", help="compare, write nothing")
    check = parser.parse_args(argv).check
    missing: list[str] = []
    stale = 0
    for rel, text in _pages(missing).items():
        target = DOCS_DIR / rel
        if not check:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(text.encode("utf-8"))
            continue
        current = target.read_text(encoding="utf-8") if target.is_file() else ""
        if current != text:
            stale += 1
            print(f"docs/{rel} is stale; run scripts/docs/gen_reference.py")
            old, new = current.splitlines(keepends=True), text.splitlines(keepends=True)
            names = f"docs/{rel} (committed)", f"docs/{rel} (generated)"
            sys.stdout.writelines(difflib.unified_diff(old, new, *names))
    if check:
        for table, field in (name.split(".", 1) for name in missing):
            print(f"warning: {table}: field {field} has no description", file=sys.stderr)
    return 1 if stale else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
