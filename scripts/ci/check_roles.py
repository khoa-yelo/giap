#!/usr/bin/env python3
"""Enforce the separation of test and implementation roles (GIAP_SPEC.md R2, §14.6).

Fails if, within the PR, one Agent-Role changes both src/ (or workflow/) and test files,
an implementer commit modifies an existing test file, or a test-author commit touches
src/ or workflow/. Commits without an Agent-Role trailer fail too.
"""

from __future__ import annotations

import re
import subprocess
import sys
from collections import defaultdict

CODE = ("src/", "workflow/")
TESTS = ("tests/", "workflow/tests/")  # nf-test specs must live under workflow/tests/
EXEMPT_TESTS = (
    "tests/data/recorded/",  # implementers may add recorded fixtures
    "tests/data/golden/",  # golden outputs are regenerated by the code (GIAP_UPDATE_GOLDEN=1)
    "tests/sim/",  # the simulator (giapsim) is tooling the implementer owns, not tests
    # Real-tool harness run by scripts/slurm/nf_process_real.sbatch (no assertions; the comparison
    # lives in scripts/dev/nf_real_compare.py): tooling, like giapsim.
    "workflow/tests/real/",
    # Generated snapshot of the live step registry (equality pinned by
    # test_step_registry_fixture_equals_the_live_registry): regenerated by whoever registers a step.
    "workflow/tests/data/annotate/step_registry.json",
    "workflow/tests/data/mapping/step_registry.json",
    # The calibration harness (M4-05 spec) is tooling the implementer owns, like giapsim.
    "tests/calibration/_criteria.py",
    "tests/calibration/conftest.py",
)


def git(*args: str) -> str:
    return subprocess.run(["git", *args], capture_output=True, text=True, check=True).stdout


def main() -> int:
    base = sys.argv[1] if len(sys.argv) > 1 else "origin/main"
    shas = git("rev-list", "--no-merges", f"{base}..HEAD").split()
    touched: dict[str, set[str]] = defaultdict(set)
    errors = []
    for sha in shas:
        body = git("log", "-1", "--format=%B", sha)
        m = re.search(r"^Agent-Role:\s*(\S+)", body, re.M)
        if not m:
            errors.append(f"{sha[:8]}: missing Agent-Role trailer")
            continue
        role = m.group(1)
        status = git("diff-tree", "--no-commit-id", "--name-status", "-r", "-M", sha).splitlines()
        for line in status:
            fields = line.split("\t")
            kind, paths = fields[0], fields[1:]
            for path in paths:  # a rename lists the old and the new path
                is_test_path = path.startswith(TESTS)
                is_code = path.startswith(CODE) and not is_test_path
                is_test = is_test_path and not path.startswith(EXEMPT_TESTS)
                if is_code:
                    touched[role].add("code")
                if is_test:
                    touched[role].add("tests")
                if role == "implementer" and is_test and kind[:1] in {"M", "D", "R", "T"}:
                    errors.append(f"{sha[:8]}: implementer changed existing test {path} ({kind})")
                if role == "test-author" and is_code:
                    errors.append(f"{sha[:8]}: test-author touched {path}")
    for role, kinds in touched.items():
        if kinds == {"code", "tests"} and role not in {"lead"}:
            errors.append(f"role {role} changed both code and tests in this PR")
    for e in errors:
        print(e)
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main())
