"""Write ``mass_equivalents.tsv``, the default-tolerance mass-equivalence list (GIAP_SPEC.md
§7.5.3, Appendix B.5; docs/specs/M7-05-variant-flags.md rule 1, lead decision 2).

``python -m giap.data.build_mass_equivalents [--out PATH]`` writes the list of
``giap.mapping.masses.mass_equivalents()`` next to this module, or to ``PATH``. The file is the
reviewed artefact; the run time recomputes the list at the configured tolerance and never reads it.
"""

from __future__ import annotations

import argparse
from collections.abc import Sequence
from pathlib import Path

from giap.mapping.masses import DEFAULT_TOL_DA, DELTA_DECIMALS, mass_equivalents

DEFAULT_OUT = Path(__file__).with_name("mass_equivalents.tsv")
HEADER = ("left", "right", "delta_da", "kind")


def render(tol_da: float = DEFAULT_TOL_DA) -> str:
    """The TSV text: comment lines, the header row, one row per entry in list order. Pure."""
    lines = [
        "# Generated by giap.data.build_mass_equivalents from the GIAP_SPEC.md Appendix B.5",
        "# residue and modification masses; do not edit by hand.",
        f"# Tolerance {tol_da} Da; delta_da = |m(left) - m(right)| in Da.",
        "\t".join(HEADER),
    ]
    lines += [
        f"{e.left}\t{e.right}\t{e.delta_da:.{DELTA_DECIMALS}f}\t{e.kind}"
        for e in mass_equivalents(tol_da)
    ]
    return "\n".join(lines) + "\n"


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="python -m giap.data.build_mass_equivalents")
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT, help="output TSV path")
    args = parser.parse_args(argv)
    args.out.write_text(render(), encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
